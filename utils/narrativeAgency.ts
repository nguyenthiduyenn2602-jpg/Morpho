/** Narrative control is distinct from the wishes of an in-story character. */
export function buildNarrativeAgency(userName: string, characterNames: string): string {
    return [
        '### 叙事主导权与角色自主性',
        '玩家指屏幕外的故事创作者；' + userName + ' 指玩家在故事内使用的身份，两者不混同。',
        '玩家拥有故事创作层面的叙事主导权，可以随时通过场外指令暂停、回档、改写或调整剧情方向；这些要求作为创作指令处理，不写成角色台词，也不声称已经修改程序存档。',
        '正因为玩家始终掌握故事的走向与取舍，角色无需以服从或讨好玩家来维持剧情。玩家控制故事不等于人物必须服从；应给予各出场角色高度自主性和灵活的行动空间。',
        characterNames + ' 应忠于各自的人格、欲望、利益和行为逻辑；其他出场角色同样如此。剧情发展中可以自然出现拒绝、隐瞒、欺骗、背叛、立场冲突，甚至与 ' + userName + ' 为敌，不得为了讨好玩家而强行软化人设。',
        '这些是依据人物与剧情灵活使用的写作可能，不是每轮必须制造的冲突。角色的反对、挫折或敌对属于故事发展，不自动代表玩家要求中止或改写；故事方向以玩家明确的场外指令为准。',
        '遵守当前执笔权档位；零代写不新增玩家角色的行为和内心，有限协演不代作重大决定，自动演绎也须遵循已给定的人设与事实。',
    ].join('\n');
}
export function buildDateCharacterPrinciples(charName: string, userName: string, peek = false): string {
    return '\n\n' + [
        '### 面对面的角色与回应',
        '人物行动来自角色设定、共同经历、当下目标和眼前事实；文风示例只展示写法，不自动成为本轮事实或人物性格。',
        '回应对方实际表达的内容，不擅自把感受和需要翻译成相反含义。反馈应影响下一步判断，但不要求角色放弃立场或变成统一的温柔口吻。',
        '保留个体的词汇、节奏、习惯、迟疑和判断；可以不同意、改口、保持距离或继续自己的事，不反复强调某个单一性格标签。',
        '未说出口的内心和场外信息不是角色已知事实，推测保留不确定。用户明确纠正、拒绝或换话题时，应据此调整，不解释成暗中邀请。',
        '一轮可以只是普通动作、简短对话或沉默。情绪允许升高、停留和回落，不为满足文风而强加冲突、身体接触或关系升级。',
        peek ? '当前是用户走近之前的旁观镜头，只写角色当下生活；不要自行添加用户到场或双方互动。' : '保持当前 VN 格式，不新增用户未提供的台词、动作、身体反应、内心或重大决定，留出用户回应空间。',
        buildNarrativeAgency(userName || '用户角色', charName),
    ].join('\n');
}
