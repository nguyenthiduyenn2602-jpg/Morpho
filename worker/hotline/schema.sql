CREATE TABLE IF NOT EXISTS letters (id TEXT PRIMARY KEY, digest TEXT NOT NULL, status TEXT NOT NULL, created TEXT NOT NULL, body TEXT NOT NULL, is_read INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS letters_order ON letters(status,created DESC,id DESC);
CREATE TABLE IF NOT EXISTS sessions (id TEXT PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS limits (id TEXT PRIMARY KEY,n INTEGER NOT NULL,expires INTEGER NOT NULL);
